/** Libellé de l'infobulle : « Nom, Capitale / Capitale » (comme la bêta). */
export function countryLabel(country: Country): string {
  if (country.capitals.length === 0) return country.name;
  return `${country.name}, ${country.capitals.map((c) => c.name).join(" / ")}`;
}
